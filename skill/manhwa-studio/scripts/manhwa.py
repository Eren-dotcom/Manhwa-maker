#!/usr/bin/env python3
"""
manhwa.py -- the production CLI for AI-assisted manhwa / webtoon pipelines.

  init      scaffold a project (blank or from the reference pilot)
  prompts   emit a per-tool prompt pack + machine-readable job queue
  assemble  panels -> vertical strip -> platform tiles + manifest + preview
  check     run the QC gates on the script and the assembled strip
  status    where the production stands and what to do next
  plan      staggered weekly production calendar (studio logic)

Everything is plain JSON + PNG on disk. No server, no database, no lock-in.
Docs: ../../references/   Repo guide: ../../../docs/02-pipeline-step-by-step.md
"""
from __future__ import annotations

